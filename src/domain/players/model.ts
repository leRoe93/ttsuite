/**
 * Shared player model used by every tool (team planner, tournament planner, future tools).
 * Pure data – no UI state. Optional fields stay optional: importers never invent values.
 */

export type Gender = 'm' | 'w' | 'd';

/** Where a record came from. New adapters add their own id here. */
export type SourceId = 'click-tt-xml' | 'click-tt-table' | 'mytischtennis-table' | 'generic-table' | 'manual' | 'backup';

/** Kader status raises lineup tolerances (HTTV/BeTTV Infoblätter: D-Kader or higher). */
export type KaderStatus = 'none' | 'd-kader-plus';

/**
 * A Sperrvermerk (SPV) that already exists, e.g. issued at the start of the Vorrunde and
 * still valid in the Rückrunde. Planned/new SPVs are *derived* by the rule engine and are not stored here.
 */
export interface ExistingSperrvermerk {
  /** Team number (1 = 1st team) the player was registered in when the SPV was issued. */
  teamNumber: number;
  /** Free text, e.g. "VR 2026/27 – vom Spielleiter vergeben". */
  note?: string;
}

/** Rule-relevant attributes. Kept separate from display data and UI state. */
export interface PlayerRuleAttributes {
  /** Q-TTR value of the relevant cut-off date (11.05. for VR, 11.12. for RR). */
  qttr?: number;
  /** Nachwuchsspieler (e.g. with SBEM/JES) listed in an adult lineup – raises tolerances. */
  nachwuchs?: boolean;
  kader?: KaderStatus;
  /** Existing SPV carried over from an earlier half-season. */
  sperrvermerk?: ExistingSperrvermerk;
  /** false = no playing eligibility (Spielberechtigung) for this club/age class. undefined = unknown. */
  eligible?: boolean;
  eligibilityNote?: string;
}

export interface PlayerImportMeta {
  source: SourceId;
  importedAt: string; // ISO timestamp
  fileName?: string;
  /** Source-specific identifier, e.g. click-TT tournament player id "PLAYER7" (not stable across downloads). */
  sourceRef?: string;
}

export interface Player {
  /** Local unique id, generated by the app. */
  id: string;
  firstName: string;
  lastName: string;
  club?: string;
  clubNr?: string;
  /** Current TTR (may differ from Q-TTR). */
  ttr?: number;
  gender?: Gender;
  birthYear?: number;
  /** DTTB licence number / Spielerlizenz-Nr. */
  licenceNr?: string;
  /** click-TT person number, e.g. "NU1005321". */
  internalNr?: string;
  /** Extra click-TT person attributes that must be preserved for a faithful round-trip. */
  clickTtPerson?: Record<string, string>;
  rules: PlayerRuleAttributes;
  meta: PlayerImportMeta;
}

export function fullName(p: Pick<Player, 'firstName' | 'lastName'>): string {
  return [p.firstName, p.lastName].filter(Boolean).join(' ').trim();
}

export function sortName(p: Pick<Player, 'firstName' | 'lastName'>): string {
  return [p.lastName, p.firstName].filter(Boolean).join(', ');
}

/** Rating used for strength ordering: Q-TTR if known, else nothing (current TTR is *not* a substitute). */
export function lineupRating(p: Player): number | undefined {
  return p.rules.qttr;
}

/** Rating used for tournament seeding: prefers Q-TTR, falls back to TTR. */
export function seedingRating(p: Player): number | undefined {
  return p.rules.qttr ?? p.ttr;
}

let counter = 0;
export function newId(prefix = 'p'): string {
  counter = (counter + 1) % 1_000_000;
  const rnd = Math.random().toString(36).slice(2, 8);
  return `${prefix}_${Date.now().toString(36)}${counter.toString(36)}${rnd}`;
}
